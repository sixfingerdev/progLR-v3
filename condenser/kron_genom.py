"""
Kronecker-based parametric weight generation.
A tiny "Genom" recurrent network generates weight matrices on-the-fly
via Kronecker decomposition. This gives extreme compression ratios
while maintaining expressivity.

Key idea: W_l = sum_{i=1..r} kron(A_{l,i}, B_{l,i})
where A, B are generated by the evolving Genom state.
The full weight matrix exists only during the forward pass of that layer.
"""

import torch
import torch.nn as nn
import torch.nn.functional as F
import math


class KroneckerGenom(nn.Module):
    """
    Recurrent network that evolves a state and generates
    Kronecker factors for weight construction.
    """
    def __init__(
        self,
        state_dim: int = 256,
        hidden_dim: int = 1024,
        kronecker_rank: int = 8,
        factor_dim: int = 32,
        n_generations: int = 64,
    ):
        super().__init__()
        self.state_dim = state_dim
        self.hidden_dim = hidden_dim
        self.kronecker_rank = kronecker_rank
        self.factor_dim = factor_dim
        self.n_generations = n_generations

        self.state_init = nn.Parameter(torch.randn(1, state_dim) * 0.02)

        self.state_cell = nn.LSTMCell(state_dim, state_dim)

        n_factors_per_term = 4
        values_per_layer = kronecker_rank * 2 * n_factors_per_term * factor_dim * factor_dim

        self.output_proj = nn.Sequential(
            nn.Linear(state_dim, state_dim),
            nn.ReLU(),
            nn.Linear(state_dim, values_per_layer),
        )

        self.factor_cache = {}

    def forward(self, n_layers: int, device: torch.device) -> list[torch.Tensor]:
        h = self.state_init.expand(1, -1).to(device)
        c = torch.zeros(1, self.state_dim, device=device)
        weights = []

        for l in range(n_layers):
            h, c = self.state_cell(h, (h, c))
            raw = self.output_proj(h)

            W = self._construct_weight(raw)
            weights.append(W)

        return weights

    def _construct_weight(self, raw: torch.Tensor) -> torch.Tensor:
        r = self.kronecker_rank
        fd = self.factor_dim
        g = 2 * 4 * fd * fd

        parts = raw[0].view(r, 2, 4, fd, fd)

        total_dim = fd ** 4
        W = torch.zeros(total_dim, total_dim, device=raw.device)

        for i in range(r):
            term = torch.ones(1, 1, device=raw.device)
            for j in range(4):
                factor = parts[i, 0, j] @ parts[i, 1, j].T
                term = torch.kron(term, factor)
            W = W + term

        return W


class KronLaWS(nn.Module):
    """
    Full model using KroneckerGenom for parameter-efficient training.
    """
    def __init__(
        self,
        vocab_size: int = 50000,
        hidden_dim: int = 1024,
        num_layers: int = 12,
        state_dim: int = 256,
        kronecker_rank: int = 8,
        factor_dim: int = 16,
    ):
        super().__init__()
        self.hidden_dim = hidden_dim
        self.num_layers = num_layers

        fd = factor_dim
        while fd ** 4 < hidden_dim:
            fd += 1
        factor_dim = fd
        self.factor_dim = factor_dim

        self.genom = KroneckerGenom(
            state_dim=state_dim,
            hidden_dim=hidden_dim,
            kronecker_rank=kronecker_rank,
            factor_dim=factor_dim,
        )

        self.token_embedding = nn.Embedding(vocab_size, hidden_dim)
        self.norms = nn.ModuleList([
            nn.LayerNorm(hidden_dim) for _ in range(num_layers)
        ])
        self.lm_head = nn.Linear(hidden_dim, vocab_size, bias=False)
        self.token_embedding.weight = self.lm_head.weight

    def forward(self, input_ids: torch.Tensor) -> torch.Tensor:
        B, T = input_ids.shape
        x = self.token_embedding(input_ids)
        weights = self.genom(self.num_layers, x.device)

        for l in range(self.num_layers):
            residual = x
            x = self.norms[l](x)

            W = weights[l]
            actual_h = min(W.shape[0], self.hidden_dim)
            W_cropped = W[:actual_h, :actual_h]
            x_proj = F.linear(x, W_cropped)
            x = F.relu(x_proj + residual)

        x = self.lm_head(x)
        return x

    def count_all_params(self):
        trainable = sum(p.numel() for p in self.parameters() if p.requires_grad)
        return trainable

    def effective_params(self):
        return self.num_layers * self.hidden_dim * self.hidden_dim

    def memory_report(self):
        trainable = self.count_all_params()
        eff = self.effective_params()
        return {
            'trainable_m': trainable / 1e6,
            'effective_m': eff / 1e6,
            'compression_ratio': eff / trainable if trainable > 0 else float('inf'),
            'vram_gb_fp16': trainable * 2 / 1e9,
            'vram_gb_optim': trainable * 8 / 1e9,
            'total_vram_gb': trainable * 10 / 1e9,
        }
